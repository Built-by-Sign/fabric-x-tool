func TestFabricCACopyFileCreatesDestinationDirectory(t *testing.T) {
	srcDir := t.TempDir()
	src := filepath.Join(srcDir, "source.pem")
	if err := os.WriteFile(src, []byte("cert"), 0644); err != nil {
		t.Fatalf("write source: %v", err)
	}

	dst := filepath.Join(t.TempDir(), "nested", "dir", "dest.pem")
	g := NewFabricCAGenerator(&config.NetworkConfig{}, t.TempDir(), "quiet", false)
	if err := g.copyFile(src, dst); err != nil {
		t.Fatalf("copyFile: %v", err)
	}

	got, err := os.ReadFile(dst)
	if err != nil {
		t.Fatalf("read destination: %v", err)
	}
	if string(got) != "cert" {
		t.Fatalf("unexpected destination contents: %q", string(got))
	}
}

