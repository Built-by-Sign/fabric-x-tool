func TestFabricCANormalizeEnrolledMSPMatchesCryptogenLayout(t *testing.T) {
	mspDir := t.TempDir()
	if err := os.MkdirAll(filepath.Join(mspDir, "signcerts"), 0755); err != nil {
		t.Fatalf("create signcerts: %v", err)
	}
	if err := os.MkdirAll(filepath.Join(mspDir, "cacerts"), 0755); err != nil {
		t.Fatalf("create cacerts: %v", err)
	}
	if err := os.WriteFile(filepath.Join(mspDir, "signcerts", "cert.pem"), []byte("cert"), 0644); err != nil {
		t.Fatalf("write cert: %v", err)
	}
	if err := os.WriteFile(filepath.Join(mspDir, "cacerts", "ca-host-7054.pem"), []byte("ca"), 0644); err != nil {
		t.Fatalf("write ca: %v", err)
	}

	g := NewFabricCAGenerator(&config.NetworkConfig{}, t.TempDir(), "quiet", false)
	if err := g.normalizeEnrolledMSP(mspDir, "org1.example.com", "Admin@org1.example.com"); err != nil {
		t.Fatalf("normalizeEnrolledMSP: %v", err)
	}

	for _, want := range []string{
		filepath.Join(mspDir, "signcerts", "Admin@org1.example.com-cert.pem"),
		filepath.Join(mspDir, "cacerts", "ca.org1.example.com-cert.pem"),
	} {
		if _, err := os.Stat(want); err != nil {
			t.Fatalf("expected normalized file %s: %v", want, err)
		}
	}
}

