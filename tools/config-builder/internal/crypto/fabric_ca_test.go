func TestWriteFabricCAClientConfigUsesVendoredTemplate(t *testing.T) {
	g := NewFabricCAGenerator(&config.NetworkConfig{}, t.TempDir(), "quiet", false)
	configPath := filepath.Join(t.TempDir(), "nested", "fabric-ca-client-config.yaml")

	if err := g.writeFabricCAClientConfig(configPath, "org1-token", "1234"); err != nil {
		t.Fatalf("writeFabricCAClientConfig: %v", err)
	}

	data, err := os.ReadFile(configPath)
	if err != nil {
		t.Fatalf("read rendered config: %v", err)
	}
	rendered := string(data)

	for _, want := range []string{
		"bccsp:",
		"default: PKCS11",
		"Library: ./libkms_pkcs11.so",
		"Label: org1-token",
		"Pin: 1234",
		"Hash: SHA2",
		"Security: 256",
	} {
		if !strings.Contains(rendered, want) {
			t.Fatalf("rendered config missing %q:\n%s", want, rendered)
		}
	}
}

func TestWriteFabricCAClientConfigAllowsLibraryOverride(t *testing.T) {
	t.Setenv("FABRIC_CA_CLIENT_PKCS11_LIBRARY", "/opt/fabric/libkms_pkcs11.so")

	g := NewFabricCAGenerator(&config.NetworkConfig{}, t.TempDir(), "quiet", false)
	configPath := filepath.Join(t.TempDir(), "fabric-ca-client-config.yaml")

	if err := g.writeFabricCAClientConfig(configPath, "token", "pin"); err != nil {
		t.Fatalf("writeFabricCAClientConfig: %v", err)
	}

	data, err := os.ReadFile(configPath)
	if err != nil {
		t.Fatalf("read rendered config: %v", err)
	}
	if !strings.Contains(string(data), "Library: /opt/fabric/libkms_pkcs11.so") {
		t.Fatalf("expected overridden library path, got:\n%s", string(data))
	}
}
